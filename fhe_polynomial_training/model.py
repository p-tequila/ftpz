"""Integer-only two-layer polynomial network and its one-example SGD update."""

from __future__ import annotations

import numpy as np

N_FEATURES = 2
N_HIDDEN = 2


def forward(x, w1, b1, w2, b2):
    """Return the integer prediction of x -> square(xW1+b1) -> hW2+b2."""
    z = x @ w1 + b1
    hidden = z * z
    return hidden @ w2 + b2


def training_step(x, y, w1, b1, w2, b2):
    """One bounded integer SGD update; every argument is an FHE circuit input.

    Integer divisions are fixed learning-rate scalers, not neural-network activations.
    The asymmetrical small rates deliberately keep this teaching example in a narrow,
    compiler-calibrated range.  A serious model needs careful quantization and validation.
    """
    z = x @ w1 + b1
    hidden = z * z
    prediction = hidden @ w2 + b2
    error = prediction - y

    gradient_w2 = hidden.reshape(N_HIDDEN, 1) * error.reshape(1, 1)
    gradient_b2 = error
    gradient_z = (2 * z) * (w2.reshape(N_HIDDEN) * error.reshape(1))
    gradient_w1 = x.reshape(N_FEATURES, 1) * gradient_z.reshape(1, N_HIDDEN)
    gradient_b1 = gradient_z

    # The output layer has a unit step in this tiny example.  The other parameters
    # update too, but use smaller integer steps to avoid immediate overflow.
    return (
        w1 - gradient_w1 // 16,
        b1 - gradient_b1 // 16,
        w2 - gradient_w2,
        b2 - gradient_b2 // 4,
    )


def initial_parameters():
    """Small non-zero integer parameters: shape (2,2), (2,), (2,1), (1,)."""
    return (
        np.array([[1, 0], [0, 1]], dtype=np.int64),
        np.array([0, 0], dtype=np.int64),
        np.array([[2], [-1]], dtype=np.int64),
        np.array([0], dtype=np.int64),
    )


def synthetic_data():
    """Separate train/test records generated by y = x0**2 - x1**2."""
    x_train = np.array([[1, 0], [0, 1], [1, 1], [-1, 0]], dtype=np.int64)
    y_train = np.array([[1], [-1], [0], [1]], dtype=np.int64)
    x_test = np.array([[0, 0], [1, -1], [-1, 1]], dtype=np.int64)
    # These targets are evaluated after training: the first update changes W2 from
    # [2, -1] to [1, -1], so the trained network predicts zero on all test rows.
    y_test = np.array([[0], [0], [0]], dtype=np.int64)
    return x_train, y_train, x_test, y_test
